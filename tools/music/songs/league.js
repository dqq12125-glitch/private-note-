//   只靠「往下那一步 + 长音在推拍（不在强拍）」分开，所以 C → Ab 那一步一定要留着、听得清楚。
//   主题前面不加往上的音阶引子（巴赫《二部创意曲》），前奏改用鼓敲推拍的节奏。旧主题「5-1-3-2-1-6 | 5-1-2」和前奏的「D. Eb F」都去掉了。
