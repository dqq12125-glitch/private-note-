//   5–8 小节是往下走的三和弦长音句（第 6 小节换了个顺序 Bb D G），没有《欢乐颂》《奇异恩典》那种级进骨架；
//   B 段第 1–2 小节 C C Eb C Ab G F | D D F D Bb——同音附点 + 小三度一绕再跳上四度，
//   和《星条旗永不落》《拉德茨基》《桂河大桥》这些名进行曲的开头都不一样；
