//   C  ：Cm | Ab | Fm | Bb | Cm | Ab | F | Bb —— 攀登段：附点八分 + 十六分的进行曲步子（接着 B 段的附点）一级级往上爬，
//        F 大三和弦是重属和弦（调外的 A 是故意的），停在 Bb 上（最后一拍 Bb5，往下三度落到 A2 开头的 G5）
