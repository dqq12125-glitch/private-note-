//       低音用 GB 波形（wave）「嘭—嚓」（根音—五音），整条低音放在 D2–Eb3：三角波在 F1–Eb2 几乎没有泛音，手机喇叭上听不见，
//       wave 的泛音 + 抬高的音区能让进行曲的「嘭—嚓」在手机上也听得出来
// 结构：I(2) A(8) B(8) C(8) A2(8) → 回 A（循环 32 小节 ≈ 69 秒）
//   I  ：风琴 Eb → Ab/Eb，定音鼓一样的嗵鼓滚奏，钟琴一把扫上去；第二小节先用鼓「嗒、嗒、嗒」敲出推拍的节奏，
//        铜管 + 风琴 + 吊镲在推拍上一起「当——」（Bb 和弦的根音 Bb5，先预告主题自己的推拍音），往下三度落到主题的 G
//   A  ：回声主题「进行曲版」（SPEC §3，移到 Eb 大调）：附点放在前面、推拍留着——
//        呼 G5. Ab5 F5 Bb5~（休）| Ab5. G5 Bb5 F5~~   应 Bb5. C6 Ab5 Eb6~（休）| Ab5. G5 Bb5 Eb5~~
//        和弦 Eb | Fm7 → Bb | Eb/G → Ab | Bb7 → Eb（每小节第二个和弦换在推拍上），军鼓 + 低嗵（定音鼓）打在推拍上；
//        第 3 小节按 SPEC 走低音：G 只托第 1 拍，旋律 Ab5 那一下底下是 Eb，推拍上才是 Ab；风琴在楔子底下不放 G。
//        5–8 小节换成直的「四分 四分 二分」长音句，一级级往下（Eb6 C6 Ab5 | Bb5 D6 G5 | C6 Ab5 F5 D5 | Eb5），
//        和弦 Ab | Gm | Fm7 Bb | Eb（低音 Ab G F Bb Eb），不再推拍，让推拍只属于主题；
//        第 6 小节先 Bb5 再 D6（Ab5 → Bb5 一步上去），不从 Ab5 跨小节线跳三全音到 D6（铜管唱庄严进行曲，那一跳太拐）
//        钟琴只在二、四拍「嚓」一下（按每小节的和弦配；推拍前后和弦不一样，两下也不一样）；
//        第 2 小节第 2 拍的 Fm7 放在旋律上面（C6 Eb6 F6），不在铜管的 Bb5 两边夹成 Ab–Bb–C 的音簇
