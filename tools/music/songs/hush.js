// 嘘声团来了（The Hush Gang）
// 在哪里放：嘘声团基地、和嘘声团有关的剧情
// 情绪：反派——鬼鬼祟祟、踮着脚走。F 小调，116 bpm，轻摇摆；断奏的细方波旋律 + 拨弦 + 断奏低音，
//       风琴只在反拍「咚」一下；嘘声团想让世界安静，所以常常整个乐队突然停住（第 4、8 小节只剩一个重音，B 段结尾和 C 段几乎全静）
// 结构：I(2) A(8) B(8) A2(8) C(4) → 回 A（循环 28 小节 ≈ 58 秒）
//   I  ：只有踮脚的低音和闭镲
//   A  ：Fm | C7 | Fm | C | Fm | Bbm | Gb | C —— 「踮脚」动机：同音两下 + 上方半音一绕；第 3 小节半音一级级爬上去，第 4 小节「嘭」一下全停；
//        第 7 小节在那不勒斯和弦 Gb 上半音一路滑下来
//   B  ：Fm | C/E | Fm/Eb | D° | Db | Bbm | Gb | C —— 低音半音下行（F E Eb D Db），风琴长和弦，旋律长音往下压；结尾两拍突然全静。
//        这段旋律放在低一个八度（C4–Ab4），细方波长音不在高音区刺耳；拨弦反过来放到上面（D5–C6），像一个有点吓人的八音盒
//   A2 ：A 的旋律 + 拨弦低八度跟着一起踮脚，军鼓轻轻点；第 7 小节换成从更高处滑下来（Db5 落在风琴的 Gb 和弦上，C5 放到反拍）
//   C  ：「嘘——」：两小节几乎只剩闭镲和一点耳语，然后两下重击（Fm、Gb），最后半音一口气爬到 B 接回 A 的 C
//        （「嘘」的静默只放在 C 段前两小节；最后一小节旋律和低音都拉满到小节线——原来最后一拍全停，循环接缝前后差 7.5 dB）
// 回声主题：不用
// 调外音（E、A、B、D、Gb）是故意的半音阶和那不勒斯和弦——反派的「歪」味道
// 原创检查：A 第 1–2 小节 C C Db C Ab | G G Ab G E——音程 0 +1 -1 -4 | -1 0 +1 -1 -4，节奏 八分＋休止交替的踮脚 + 三个八分；
//   b6→5 的「叹气」是通用的小调语汇（莫扎特第 40 交响曲也有），但这里的轮廓和断奏 + 休止的节奏都不一样；
//   特意避开了《粉红豹》（下方半音倚音往上靠、摇摆长音）、《山魔王的大厅》（小调音阶一级级往上、跳回再上）、《碟中谍》（5/4 的 G G Bb C）、《大白鲨》（下方半音两个音来回）；
//   第 3 小节的半音爬升 F G Ab A Bb B C 是连奏一口气上去、没有《山魔王》那种「爬两步跳回」的形状；和现成游戏的反派组织的音乐也对不上。

const down = bar => bar.replace(/([A-G][#b]?)(\d)/g, (m, p, o) => p + (o - 1));     // 整小节降八度（拨弦跟旋律）
